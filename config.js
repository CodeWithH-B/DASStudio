#!/usr/bin/env node
/* ==================================================================
   tools/build-config.js — generate config.js from .env
   ==================================================================
   Usage:
     node tools/build-config.js                 # reads ./.env, writes ./config.js
     node tools/build-config.js --env prod.env  # a different env file
     node tools/build-config.js --check         # exit 1 if config.js is missing

   No dependencies: this must run on a bare CI image.
   ================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const envArg = args.indexOf('--env');
const envFile = envArg > -1 ? path.resolve(root, args[envArg + 1]) : path.join(root, '.env');
const checkOnly = args.includes('--check');
const outFile = path.join(root, 'config.js');

function readEnv(file) {
  const env = {};
  if (!fs.existsSync(file)) return env;
  fs.readFileSync(file, 'utf8').split(/\r?\n/).forEach((line) => {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (!m) return;
    env[m[1]] = m[2].replace(/^["']|["']$/g, '').trim();
  });
  return env;
}

const env = Object.assign({}, readEnv(envFile), process.env);
const need = ['FIREBASE_API_KEY', 'FIREBASE_AUTH_DOMAIN', 'FIREBASE_PROJECT_ID', 'FIREBASE_APP_ID'];

if (checkOnly) {
  if (!fs.existsSync(outFile)) {
    console.error('config.js is missing — run `node tools/build-config.js` before deploying.');
    process.exit(1);
  }
  console.log('config.js present.');
  process.exit(0);
}

const missing = need.filter((k) => !env[k]);
if (missing.length) {
  console.error('Missing env values: ' + missing.join(', '));
  console.error('Copy .env.example to .env and fill it in (see README.md > Setup).');
  process.exit(1);
}

const cfg = {
  apiKey: env.FIREBASE_API_KEY,
  authDomain: env.FIREBASE_AUTH_DOMAIN,
  projectId: env.FIREBASE_PROJECT_ID,
  storageBucket: env.FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID || '',
  appId: env.FIREBASE_APP_ID,
  measurementId: env.FIREBASE_MEASUREMENT_ID || ''
};

const trusted = String(env.DAS_TRUSTED_CODE || 'false').toLowerCase() === 'true';

const body = `/* Generated by tools/build-config.js — do not edit by hand.
   Everything here is PUBLIC: the Firebase web config ships to every browser.
   Security comes from Firestore rules and API key restrictions (README.md). */
window.DAS_CONFIG = {
  firebase: ${JSON.stringify(cfg, null, 4).replace(/\n/g, '\n  ')},
  trustedCode: ${trusted}
};
`;

fs.writeFileSync(outFile, body, 'utf8');
console.log('Wrote ' + path.relative(root, outFile) + ' for project "' + cfg.projectId + '".');
console.log('Reminder: add an HTTP-referrer restriction to this API key in the Firebase console.');
